let nextRequestNumber = 1100;

const simpleStage = (
  id: string,
  name: string,
  kind: WorkflowStage["kind"],
  health: WorkflowStage["health"],
  statusLabel: string,
  count: number,
  countLabel: string,
  ownerId: string,
  sla: number,
  moved: number | undefined,
  description: string,
  itemTitles: string[],
): WorkflowStage => ({
  id,
  name,
  kind,
  description,
  health,
  statusLabel,
  count,
  countLabel,
  ownerId,
  sla,
  overdue: health === "attention" || health === "critical" ? Math.max(1, Math.round(count * 0.3)) : 0,
  time: sla > 0 ? `${(sla / 25).toFixed(1)} h` : "—",
  timeNote: sla > 0 ? (sla >= 90 ? "within target" : "target 3.6 h · over") : "no data",
  movedToday: moved,
  metrics: [
    { label: "Avg. time in stage", value: `${(sla / 25).toFixed(1)} h`, hint: "Rolling 30 days", tone: sla > 90 ? "good" : sla > 80 ? "warn" : "bad" },
    { label: "SLA compliance", value: `${sla}%`, hint: "Target 90%", tone: sla > 90 ? "good" : sla > 80 ? "warn" : "bad" },
    { label: "In stage", value: String(count), hint: countLabel, tone: "neutral" },
    { label: "Handled today", value: String(Math.max(2, Math.round(count * 0.6))), hint: "Demo figure", tone: "neutral" },
  ],
  items: itemTitles.map((t, i) => item(`#${nextRequestNumber++}`, t, ownerId, `${i + 1} h`, i === 0 ? "high" : "medium")),
  activity: [
    act(`${id}-1`, `${itemTitles[0]} moved into ${name}`, "12 min ago"),
    act(`${id}-2`, `${name} owner updated the checklist`, "1 h ago", ownerId),
  ],
});

